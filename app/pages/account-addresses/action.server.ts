import type {CustomerAddressInput} from '@shopify/hydrogen/customer-account-api-types';
import {data} from 'react-router';
import type {Route} from '../../routes/+types/($locale).account.addresses';
import {syncCustomerPhone} from '~/lib/customer-phone.server';
import {
  UPDATE_ADDRESS_MUTATION,
  DELETE_ADDRESS_MUTATION,
  CREATE_ADDRESS_MUTATION,
} from '~/graphql/customer-account/CustomerAddressMutations';

export async function action({request, context}: Route.ActionArgs) {
  const {customerAccount} = context;
  const fr = new URL(request.url).pathname.split('/')[1] !== 'en';

  try {
    const form = await request.formData();

    const addressId = form.has('addressId')
      ? String(form.get('addressId'))
      : null;
    if (!addressId) {
      throw new Error(
        fr
          ? 'Une adresse doit être sélectionnée.'
          : 'You must provide an address id.',
      );
    }

    // this will ensure redirecting to login never happen for mutatation
    const isLoggedIn = await customerAccount.isLoggedIn();
    if (!isLoggedIn) {
      return data(
        {
          error: {
            [addressId]: fr
              ? 'Votre session a expiré. Reconnectez-vous.'
              : 'Your session has expired. Sign in again.',
          },
        },
        {
          status: 401,
        },
      );
    }

    const defaultAddress = form.has('defaultAddress')
      ? String(form.get('defaultAddress')) === 'on'
      : false;
    const address: CustomerAddressInput = {};
    const keys: (keyof CustomerAddressInput)[] = [
      'address1',
      'address2',
      'city',
      'company',
      'territoryCode',
      'firstName',
      'lastName',
      'phoneNumber',
      'zoneCode',
      'zip',
    ];

    for (const key of keys) {
      const value = form.get(key);
      if (typeof value === 'string') {
        address[key] = value;
      }
    }

    switch (request.method) {
      case 'POST': {
        // handle new address creation
        try {
          const {data, errors} = await customerAccount.mutate(
            CREATE_ADDRESS_MUTATION,
            {
              variables: {
                address,
                defaultAddress,
                language: customerAccount.i18n.language,
              },
            },
          );

          if (errors?.length) {
            throw new Error(errors[0].message);
          }

          if (data?.customerAddressCreate?.userErrors?.length) {
            throw new Error(data?.customerAddressCreate?.userErrors[0].message);
          }

          if (!data?.customerAddressCreate?.customerAddress) {
            throw new Error(
              fr
                ? 'La création de l’adresse a échoué.'
                : 'Address creation failed.',
            );
          }

          return {
            error: null,
            addressId,
            createdAddress: data?.customerAddressCreate?.customerAddress,
            defaultAddress,
            phoneSyncWarning: !await syncCustomerPhone({
              customerAccount,
              env: context.env,
              addressId: data.customerAddressCreate.customerAddress.id,
              phoneNumber: address.phoneNumber,
              territoryCode: address.territoryCode,
            }),
          };
        } catch (error: unknown) {
          if (error instanceof Error) {
            return data(
              {error: {[addressId]: error.message}},
              {
                status: 400,
              },
            );
          }
          return data(
            {error: {[addressId]: error}},
            {
              status: 400,
            },
          );
        }
      }

      case 'PUT': {
        // handle address updates
        try {
          const {data, errors} = await customerAccount.mutate(
            UPDATE_ADDRESS_MUTATION,
            {
              variables: {
                address,
                addressId: decodeURIComponent(addressId),
                defaultAddress,
                language: customerAccount.i18n.language,
              },
            },
          );

          if (errors?.length) {
            throw new Error(errors[0].message);
          }

          if (data?.customerAddressUpdate?.userErrors?.length) {
            throw new Error(data?.customerAddressUpdate?.userErrors[0].message);
          }

          if (!data?.customerAddressUpdate?.customerAddress) {
            throw new Error(
              fr
                ? 'La mise à jour de l’adresse a échoué.'
                : 'Address update failed.',
            );
          }

          return {
            error: null,
            addressId,
            updatedAddress: address,
            defaultAddress,
            phoneSyncWarning: !await syncCustomerPhone({
              customerAccount,
              env: context.env,
              addressId: data.customerAddressUpdate.customerAddress.id,
              phoneNumber: address.phoneNumber,
              territoryCode: address.territoryCode,
            }),
          };
        } catch (error: unknown) {
          if (error instanceof Error) {
            return data(
              {error: {[addressId]: error.message}},
              {
                status: 400,
              },
            );
          }
          return data(
            {error: {[addressId]: error}},
            {
              status: 400,
            },
          );
        }
      }

      case 'DELETE': {
        // handles address deletion
        try {
          const {data, errors} = await customerAccount.mutate(
            DELETE_ADDRESS_MUTATION,
            {
              variables: {
                addressId: decodeURIComponent(addressId),
                language: customerAccount.i18n.language,
              },
            },
          );

          if (errors?.length) {
            throw new Error(errors[0].message);
          }

          if (data?.customerAddressDelete?.userErrors?.length) {
            throw new Error(data?.customerAddressDelete?.userErrors[0].message);
          }

          if (!data?.customerAddressDelete?.deletedAddressId) {
            throw new Error(
              fr
                ? 'La suppression de l’adresse a échoué.'
                : 'Address deletion failed.',
            );
          }

          return {error: null, deletedAddress: addressId};
        } catch (error: unknown) {
          if (error instanceof Error) {
            return data(
              {error: {[addressId]: error.message}},
              {
                status: 400,
              },
            );
          }
          return data(
            {error: {[addressId]: error}},
            {
              status: 400,
            },
          );
        }
      }

      default: {
        return data(
          {
            error: {
              [addressId]: fr
                ? 'Méthode non autorisée.'
                : 'Method not allowed.',
            },
          },
          {
            status: 405,
          },
        );
      }
    }
  } catch (error: unknown) {
    if (error instanceof Error) {
      return data(
        {error: error.message},
        {
          status: 400,
        },
      );
    }
    return data(
      {error},
      {
        status: 400,
      },
    );
  }
}

